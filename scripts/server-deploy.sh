#!/usr/bin/env bash
# Runs ON THE SERVER, called by scripts/deploy.sh with an unpacked release.
#
# Layout on FourSys (HestiaCP):
#   ~/web/<domain>/private/bukidbasket/   app code + .env.local (not web-reachable,
#                                         but inside PHP's open_basedir)
#   ~/web/<domain>/public_html/           copy of public/ + a shim index.php that
#                                         loads the real front controller
set -euo pipefail

STAGE="$1"
SHA="${2:-unknown}"
case "$STAGE" in "$HOME"/tmp/deploy.*) ;; *) echo "Unexpected stage dir: $STAGE" >&2; exit 1 ;; esac
trap 'rm -rf "$STAGE"' EXIT
DOMAIN="${DEPLOY_DOMAIN:-orange-cobra-186442.foursyscloud.com}"
SITE="$HOME/web/$DOMAIN"
APP="$SITE/private/bukidbasket"
WEB="$SITE/public_html"

[ -d "$SITE" ] || { echo "No site folder at $SITE" >&2; exit 1; }

echo "-> Checking the release (php scripts/verify.php)"
php "$STAGE/scripts/verify.php"

echo "-> Syncing app code to $APP"
mkdir -p "$APP"
rsync -a --delete \
  --exclude=/.env --exclude=/.env.local \
  "$STAGE/" "$APP/"

echo "-> Syncing public files to $WEB"
rsync -a --delete \
  --exclude=/index.php --exclude=/robots.txt \
  "$STAGE/public/" "$WEB/"

cat > "$WEB/index.php" <<'PHP'
<?php
// Generated by scripts/server-deploy.sh. The real front controller lives outside the web root.
require __DIR__ . '/../private/bukidbasket/public/index.php';
PHP

echo "$SHA $(date '+%Y-%m-%d %H:%M:%S %Z')" > "$APP/REVISION"

if [ ! -f "$APP/.env.local" ]; then
    echo "WARNING: $APP/.env.local is missing; the site cannot reach the database yet." >&2
fi

echo "Deployed $SHA to https://$DOMAIN"
